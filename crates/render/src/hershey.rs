//! OpenSCAD's stroke font for the scale-marker labels
//! (`src/glview/hershey.cc`): the Simplex Roman Hershey glyphs for ASCII
//! 32 to 126, and the layout of `hershey::TextWidth` and
//! `hershey::DrawTextHershey`. OpenSCAD draws axis numbers with these as
//! GL line strips, not with a font rasteriser, so the same strokes give the
//! same labels here with no font file (the WASM build has no file system).
//! Snapshots use it for their annotations too.
//!
//! The glyph data is a transcoding of the Hershey fonts by Dr. A. V.
//! Hershey (U. S. National Bureau of Standards), as distributed by James
//! Hurt (Cognition, Inc.), under their permissive use and redistribution
//! licence (<https://emergent.unpythonic.net/software/hershey>).

/// One glyph: its advance and its pen positions, `(-1, -1)` lifting the
/// pen.
struct Glyph {
    width: i8,
    ops: &'static [(i8, i8)],
}

/// Text alignment about the anchor (`hershey::TextAlign`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Align {
    Left,
    Center,
    Right,
}

fn glyph(c: char) -> Option<&'static Glyph> {
    let c = u32::from(c);
    (32..=126).contains(&c).then(|| &SIMPLEX[(c - 32) as usize])
}

/// `hershey::TextWidth`: the widest line at `size` (the glyphs are about
/// 25 units tall).
pub fn text_width(s: &str, size: f32) -> f32 {
    let size = size / 25.0;
    let mut longest = 0.0f32;
    let mut w = 0.0f32;
    for c in s.chars() {
        if c == '\n' {
            longest = longest.max(w);
            w = 0.0;
        }
        if let Some(g) = glyph(c) {
            w += size * f32::from(g.width);
        }
    }
    longest.max(w)
}

/// `hershey::DrawTextHershey`: the strokes of `s` anchored at `(tx, ty)`,
/// each a polyline of at least two points, computed in `f32` as OpenSCAD
/// computes them.
pub fn strokes(s: &str, tx: f32, ty: f32, align: Align, size: f32) -> Vec<Vec<[f32; 2]>> {
    let dx = match align {
        Align::Left => 0.0,
        Align::Center => -text_width(s, size) / 2.0,
        Align::Right => -text_width(s, size),
    };
    let size = size / 25.0;
    let (mut x, mut y) = (0.0f32, 0.0f32);
    let mut out: Vec<Vec<[f32; 2]>> = Vec::new();
    for c in s.chars() {
        if c == '\n' {
            y -= 30.0 * size;
            x = 0.0;
        }
        let Some(g) = glyph(c) else { continue };
        let mut pen_up = true;
        for &(px, py) in g.ops {
            if (px, py) == (-1, -1) {
                pen_up = true;
                continue;
            }
            let p = [
                tx + x + size * f32::from(px) + dx,
                ty + y + size * f32::from(py),
            ];
            if pen_up {
                out.push(vec![p]);
            } else if let Some(line) = out.last_mut() {
                line.push(p);
            }
            pen_up = false;
        }
        x += size * f32::from(g.width);
    }
    out.retain(|l| l.len() >= 2);
    out
}

